<?php

namespace App\Services\ExternalExams;

use App\Exceptions\AcademicRuleException;
use App\Models\ActivityLog;
use App\Models\ExternalCandidate;
use App\Models\ExternalCandidateSubject;
use App\Models\ExternalExamSession;
use App\Models\ExternalExamSubject;
use App\Models\ExternalResult;
use App\Models\ExternalResultChange;
use App\Models\Student;
use App\Models\User;
use App\Services\Records\RecordsSettings;
use App\Services\Records\SchoolSequence;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;

/**
 * GABECE (Grade 9) and WASSCE (Grade 12) registration and results.
 *
 * Hard rules enforced here:
 *  - `internal_reference` is generated by this system and is NOT an official number.
 *  - `official_index_number` is only ever stored exactly as supplied by the examination body; it is never
 *    generated, derived, trimmed or substituted with the internal reference.
 *  - A result becomes public/final only after verification; verified/published results change only through
 *    `correct()`, which needs a reason, the verify permission, and leaves an append-only history row.
 */
class ExternalExamService
{
    public const TYPES = ['gabece', 'wassce'];

    public const GRADE_NUMBER = ['gabece' => 9, 'wassce' => 12];

    public function __construct(protected SchoolSequence $sequence, protected RecordsSettings $settings) {}

    // ------------------------------------------------------------------ sessions & subjects

    public function createSession(array $data): ExternalExamSession
    {
        $exists = ExternalExamSession::query()->where('type', $data['type'])->where('exam_year', $data['exam_year'])->exists();
        if ($exists) {
            throw AcademicRuleException::because('err.ext.sessionExists');
        }

        return ExternalExamSession::query()->create($data + ['status' => 'open']);
    }

    public function setSessionStatus(ExternalExamSession $session, string $status): void
    {
        $session->update(['status' => $status]);
    }

    public function saveSubject(array $data, ?ExternalExamSubject $subject = null): ExternalExamSubject
    {
        $code = strtoupper(trim($data['code']));
        $dup = ExternalExamSubject::query()->where('exam_type', $data['exam_type'])->where('code', $code)
            ->when($subject, fn ($q) => $q->where('id', '!=', $subject->id))->exists();
        if ($dup) {
            throw AcademicRuleException::because('err.ext.subjectExists');
        }
        $payload = ['exam_type' => $data['exam_type'], 'code' => $code, 'name' => $data['name'], 'is_active' => (bool) ($data['is_active'] ?? true)];

        if ($subject) {
            $subject->update($payload);

            return $subject;
        }

        return ExternalExamSubject::query()->create($payload);
    }

    // ------------------------------------------------------------------ candidates

    /**
     * @param  array<int,int>  $subjectIds
     */
    public function register(User $user, ExternalExamSession $session, Student $student, array $subjectIds = [], ?string $notes = null): ExternalCandidate
    {
        if ($session->status !== 'open') {
            throw AcademicRuleException::because('err.ext.sessionClosed');
        }
        $today = now()->startOfDay();
        if (($session->registration_opens_on && $today->lt($session->registration_opens_on))
            || ($session->registration_closes_on && $today->gt($session->registration_closes_on))) {
            throw AcademicRuleException::because('err.ext.windowClosed');
        }
        if ($student->status !== 'active') {
            throw AcademicRuleException::because('err.ext.studentInactive');
        }
        // Only refuse when the level's grade number is KNOWN and wrong; unmapped levels are not guessed at.
        $grade = $student->schoolClass?->level?->grade_number;
        if ($grade !== null && $grade !== self::GRADE_NUMBER[$session->type]) {
            throw AcademicRuleException::because('err.ext.wrongGrade.'.$session->type);
        }
        if (ExternalCandidate::query()->where('session_id', $session->id)->where('student_id', $student->id)->exists()) {
            throw AcademicRuleException::because('err.ext.alreadyRegistered');
        }

        return DB::transaction(function () use ($user, $session, $student, $subjectIds, $notes) {
            $candidate = ExternalCandidate::query()->create([
                'session_id' => $session->id,
                'student_id' => $student->id,
                'internal_reference' => $this->internalReference($session),
                'status' => 'registered',
                'registered_on' => now()->toDateString(),
                'registered_by' => $user->id,
                'notes' => $notes,
                'details' => [
                    'full_name' => $student->full_name,
                    'student_number' => $student->student_number,
                    'gender' => $student->gender,
                    'date_of_birth' => $student->date_of_birth?->toDateString(),
                    'nationality' => $student->nationality,
                    'class' => $student->schoolClass?->name,
                ],
            ]);
            $this->setSubjects($candidate, $subjectIds);
            $this->audit('ext.candidate.registered', "Registered {$student->student_number} for {$session->name}");

            return $candidate;
        });
    }

    public function internalReference(ExternalExamSession $session): string
    {
        $n = $this->sequence->next($session->school_id, 'ext_candidate_'.$session->type);

        // "IC" = internal candidate reference. It is deliberately unlike an official index number.
        return sprintf('IC-%s-%d-%05d', strtoupper($session->type), $session->exam_year, $n);
    }

    /** @param array<int,int> $subjectIds */
    public function setSubjects(ExternalCandidate $candidate, array $subjectIds): void
    {
        $this->assertEditable($candidate);
        $type = $candidate->session->type;
        $valid = ExternalExamSubject::query()->where('exam_type', $type)->where('is_active', true)
            ->whereIn('id', $subjectIds)->pluck('id')->all();
        if (count($valid) !== count(array_unique($subjectIds))) {
            throw AcademicRuleException::because('err.ext.subjectInvalid');
        }

        // A subject that already has a result cannot be dropped.
        $withResults = ExternalResult::query()->where('candidate_id', $candidate->id)->pluck('subject_id')->all();
        if (array_diff($withResults, $valid) !== []) {
            throw AcademicRuleException::because('err.ext.subjectHasResult');
        }

        DB::transaction(function () use ($candidate, $valid) {
            ExternalCandidateSubject::query()->where('candidate_id', $candidate->id)->whereNotIn('subject_id', $valid)->delete();
            foreach ($valid as $id) {
                ExternalCandidateSubject::query()->firstOrCreate(['candidate_id' => $candidate->id, 'subject_id' => $id], ['school_id' => $candidate->school_id]);
            }
        });
    }

    public function setStatus(User $user, ExternalCandidate $candidate, string $status): void
    {
        if (! in_array($status, ['registered', 'confirmed', 'withdrawn'], true)) {
            throw AcademicRuleException::because('err.ext.statusInvalid');
        }
        if ($candidate->status === 'withdrawn' && $status !== 'withdrawn') {
            throw AcademicRuleException::because('err.ext.withdrawnLocked');
        }
        if ($status === 'withdrawn' && ExternalResult::query()->where('candidate_id', $candidate->id)->exists()) {
            throw AcademicRuleException::because('err.ext.hasResults');
        }
        $candidate->update(['status' => $status]);
        $this->audit('ext.candidate.status', "{$candidate->internal_reference} -> {$status}");
    }

    /**
     * Record the official index number EXACTLY as supplied. We refuse (rather than silently alter) a value that
     * is blank, padded with whitespace, contains control characters, equals/imitates our internal reference, or is
     * already held by another candidate in the same session. Changing an existing value needs the verify permission.
     */
    public function recordIndexNumber(User $user, ExternalCandidate $candidate, string $supplied, ?string $reason = null): ExternalCandidate
    {
        $this->assertEditable($candidate);
        if ($supplied === '' || trim($supplied) === '') {
            throw AcademicRuleException::because('err.ext.indexBlank');
        }
        if ($supplied !== trim($supplied) || preg_match('/[\x00-\x1F\x7F]/', $supplied) || mb_strlen($supplied) > 60) {
            throw AcademicRuleException::because('err.ext.indexFormat');
        }
        if (str_starts_with(strtoupper($supplied), 'IC-') || strcasecmp($supplied, $candidate->internal_reference) === 0) {
            throw AcademicRuleException::because('err.ext.indexIsInternal');
        }
        if ($this->indexTaken($candidate->session_id, $supplied, $candidate->id)) {
            throw AcademicRuleException::because('err.ext.indexDuplicate');
        }

        $changing = $candidate->official_index_number !== null && $candidate->official_index_number !== $supplied;
        if ($changing) {
            if (! $user->can('external_exams.verify')) {
                throw AcademicRuleException::because('err.ext.indexChangeDenied');
            }
            if (blank($reason)) {
                throw AcademicRuleException::because('err.ext.reasonRequired');
            }
        }

        $candidate->forceFill([
            'official_index_number' => $supplied,
            'index_recorded_at' => now(),
            'index_recorded_by' => $user->id,
        ])->save();

        $this->audit($changing ? 'ext.index.changed' : 'ext.index.recorded',
            "{$candidate->internal_reference}: official index ".($changing ? 'changed' : 'recorded').($reason ? " ({$reason})" : ''));

        return $candidate;
    }

    public function indexTaken(int $sessionId, string $value, ?int $exceptCandidateId = null): bool
    {
        $norm = $this->normalise($value);

        return ExternalCandidate::query()->where('session_id', $sessionId)->whereNotNull('official_index_number')
            ->when($exceptCandidateId, fn ($q) => $q->where('id', '!=', $exceptCandidateId))
            ->pluck('official_index_number')
            ->contains(fn ($v) => $this->normalise($v) === $norm);
    }

    /** Comparison only (matching/duplicate detection); stored values are never normalised. */
    public function normalise(string $value): string
    {
        return strtoupper(preg_replace('/[\s\-\/]+/', '', trim($value)));
    }

    // ------------------------------------------------------------------ results

    public function gradeList(string $examType): array
    {
        return $this->settings->gradesFor($examType);
    }

    public function enterResult(User $user, ExternalCandidate $candidate, int $subjectId, string $grade, string $source = 'manual', ?int $batchId = null): ExternalResult
    {
        $this->assertEditable($candidate);
        $this->assertGrade($candidate, $grade);

        if (! ExternalCandidateSubject::query()->where('candidate_id', $candidate->id)->where('subject_id', $subjectId)->exists()) {
            throw AcademicRuleException::because('err.ext.subjectNotRegistered');
        }

        return DB::transaction(function () use ($user, $candidate, $subjectId, $grade, $source, $batchId) {
            $existing = ExternalResult::query()->where('candidate_id', $candidate->id)->where('subject_id', $subjectId)->first();
            $event = $source === 'import' ? 'imported' : 'entered';

            if ($existing) {
                if (in_array($existing->status, ['verified', 'published'], true)) {
                    throw AcademicRuleException::because('err.ext.locked');
                }
                $old = $existing->grade;
                $existing->update(['grade' => $grade, 'status' => $event, 'source' => $source, 'import_batch_id' => $batchId]);
                $result = $existing;
            } else {
                $old = null;
                $result = ExternalResult::query()->create([
                    'candidate_id' => $candidate->id, 'subject_id' => $subjectId, 'grade' => $grade,
                    'status' => $event, 'source' => $source, 'import_batch_id' => $batchId,
                ]);
            }
            $this->log($candidate, $result, $event, $old, $grade, null, $user->id);

            return $result;
        });
    }

    public function verify(User $user, ExternalCandidate $candidate, ?array $resultIds = null): int
    {
        $this->requirePermission($user, 'external_exams.verify');
        $query = ExternalResult::query()->where('candidate_id', $candidate->id)->whereIn('status', ['entered', 'imported'])
            ->when($resultIds !== null, fn ($q) => $q->whereIn('id', $resultIds));

        $count = 0;
        foreach ($query->get() as $result) {
            $result->update(['status' => 'verified', 'verified_by' => $user->id, 'verified_at' => now()]);
            $this->log($candidate, $result, 'verified', $result->grade, $result->grade, null, $user->id);
            $count++;
        }
        if ($count === 0) {
            throw AcademicRuleException::because('err.ext.nothingToVerify');
        }
        $this->audit('ext.results.verified', "{$candidate->internal_reference}: {$count} result(s) verified");

        return $count;
    }

    /** Verify every unverified result of every candidate in a session. */
    public function verifySession(User $user, ExternalExamSession $session): int
    {
        $this->requirePermission($user, 'external_exams.verify');
        $total = 0;
        foreach (ExternalCandidate::query()->where('session_id', $session->id)->get() as $candidate) {
            try {
                $total += $this->verify($user, $candidate);
            } catch (AcademicRuleException) {
                // candidate has nothing pending
            }
        }
        if ($total === 0) {
            throw AcademicRuleException::because('err.ext.nothingToVerify');
        }

        return $total;
    }

    /**
     * Publish VERIFIED results only. If any selected candidate still holds unverified results, nothing for that
     * candidate is published and the refusal says so (no silent partial publication of a single candidate).
     *
     * @return array{published:int,skipped:int}
     */
    public function publish(User $user, ExternalExamSession $session, ?array $candidateIds = null): array
    {
        $this->requirePermission($user, 'external_exams.verify');
        $published = 0;
        $skipped = 0;

        $candidates = ExternalCandidate::query()->where('session_id', $session->id)
            ->when($candidateIds !== null, fn ($q) => $q->whereIn('id', $candidateIds))->get();

        DB::transaction(function () use ($candidates, $user, &$published, &$skipped) {
            foreach ($candidates as $candidate) {
                $results = ExternalResult::query()->where('candidate_id', $candidate->id)->get();
                if ($results->isEmpty() || $results->contains(fn ($r) => in_array($r->status, ['entered', 'imported'], true))) {
                    $skipped++;

                    continue;
                }
                foreach ($results->where('status', 'verified') as $result) {
                    $result->update(['status' => 'published', 'published_by' => $user->id, 'published_at' => now()]);
                    $this->log($candidate, $result, 'published', $result->grade, $result->grade, null, $user->id);
                    $published++;
                }
            }
        });

        if ($published === 0) {
            throw AcademicRuleException::because($skipped > 0 ? 'err.ext.unverified' : 'err.ext.nothingToPublish');
        }
        $this->audit('ext.results.published', "{$session->name}: {$published} result(s) published");

        return ['published' => $published, 'skipped' => $skipped];
    }

    /** Correction of a verified or published result: reason + verify permission; history is kept; must be re-published. */
    public function correct(User $user, ExternalResult $result, string $newGrade, string $reason): ExternalResult
    {
        $this->requirePermission($user, 'external_exams.verify');
        if (blank($reason)) {
            throw AcademicRuleException::because('err.ext.reasonRequired');
        }
        $candidate = $result->candidate()->with('session')->firstOrFail();
        $this->assertGrade($candidate, $newGrade);
        if ($result->grade === $newGrade) {
            throw AcademicRuleException::because('err.ext.noChange');
        }

        return DB::transaction(function () use ($user, $result, $candidate, $newGrade, $reason) {
            $old = $result->grade;
            $result->update([
                'grade' => $newGrade, 'status' => 'verified', 'verified_by' => $user->id, 'verified_at' => now(),
                'published_by' => null, 'published_at' => null,
            ]);
            $this->log($candidate, $result, 'corrected', $old, $newGrade, $reason, $user->id);
            $this->audit('ext.result.corrected', "{$candidate->internal_reference}: {$old} -> {$newGrade} ({$reason})");

            return $result;
        });
    }

    /** @return Collection<int,ExternalResultChange> */
    public function history(ExternalCandidate $candidate): Collection
    {
        return ExternalResultChange::query()->with(['subject', 'user'])->where('candidate_id', $candidate->id)->orderByDesc('id')->get();
    }

    // ------------------------------------------------------------------ helpers

    public function assertGrade(ExternalCandidate $candidate, string $grade): void
    {
        $candidate->loadMissing('session');
        if (! in_array($grade, $this->gradeList($candidate->session->type), true)) {
            throw AcademicRuleException::because('err.ext.gradeInvalid');
        }
    }

    protected function assertEditable(ExternalCandidate $candidate): void
    {
        $candidate->loadMissing('session');
        if ($candidate->status === 'withdrawn') {
            throw AcademicRuleException::because('err.ext.withdrawnLocked');
        }
    }

    protected function requirePermission(User $user, string $permission): void
    {
        if (! $user->can($permission)) {
            throw AcademicRuleException::because('err.ext.permission');
        }
    }

    protected function log(ExternalCandidate $candidate, ExternalResult $result, string $event, ?string $old, ?string $new, ?string $reason, ?int $userId): void
    {
        ExternalResultChange::query()->create([
            'school_id' => $candidate->school_id, 'candidate_id' => $candidate->id, 'subject_id' => $result->subject_id,
            'result_id' => $result->id, 'event' => $event, 'old_grade' => $old, 'new_grade' => $new,
            'reason' => $reason, 'user_id' => $userId,
        ]);
    }

    protected function audit(string $event, string $description): void
    {
        ActivityLog::query()->create([
            'school_id' => app(\App\Support\TenantContext::class)->id() ?? auth()->user()?->school_id,
            'user_id' => auth()->id(), 'event' => $event, 'description' => $description,
        ]);
    }
}
