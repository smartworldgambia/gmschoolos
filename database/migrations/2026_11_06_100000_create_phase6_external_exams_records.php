    /** Best-effort: derive grade numbers from level names ("Grade 7", "G7") and term order within a year. */
    private function backfillStructure(): void
    {
        foreach (DB::table('levels')->get(['id', 'name', 'code']) as $level) {
            if (preg_match('/\b(?:grade|gr|g|class|year)\s*0?(\d{1,2})\b/i', trim($level->name.' '.$level->code), $m)) {
                $n = (int) $m[1];
                if ($n >= 1 && $n <= 13) {
                    DB::table('levels')->where('id', $level->id)->update(['grade_number' => $n]);
                }
            }
        }

        $terms = DB::table('terms')->orderBy('academic_year_id')->orderBy('starts_on')->orderBy('id')->get(['id', 'academic_year_id']);
        $seq = [];
        foreach ($terms as $term) {
            $seq[$term->academic_year_id] = ($seq[$term->academic_year_id] ?? 0) + 1;
            if ($seq[$term->academic_year_id] <= 3) {
                DB::table('terms')->where('id', $term->id)->update(['sequence' => $seq[$term->academic_year_id]]);
            }
        }
    }
